"""Run the automated Poseidon well tie (agent task 03).

    python scripts/run_well_tie.py

Writes data/interim/poseidon_td/, data/processed/wavelets/, configs/calibration.yaml,
outputs/well_ties/{well}.png|.npz|.json, outputs/well_ties/summary.csv and gate G2 in outputs/decision_log.md.
"""

import sys
from datetime import datetime, timezone
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from avo import welltie  # noqa: E402

COLORS = {"near": "#4c9be8", "mid": "#43b581", "far": "#e8833a"}


def plot_tie(well, d, row, stack_defs, scales, path):
    t = d["t_ms"]
    fig, axes = plt.subplots(1, 5, figsize=(15, 9), sharey=True, gridspec_kw={"width_ratios": [1, 1, 1.3, 1.3, 1.3]})
    axes[0].plot(d["ai"], d["log_twt_ms"], color="#ef6c00", lw=0.8)
    axes[0].set_title("AI (tied time)")
    axes[1].plot(d["vpvs"], d["log_twt_ms"], color="#00838f", lw=0.8)
    axes[1].set_title("Vp/Vs")
    for k, st in enumerate(stack_defs):
        ax = axes[2 + k]
        obs = d["obs"][k] / scales[st.name]
        win = d["win_after"]
        norm = np.abs(obs[win]).max() or 1
        ax.plot(obs / norm, t, color="black", lw=1.2, label="seismic")
        ax.plot(np.where(d["win_before"], d["syn_before"][k], np.nan) / norm, t, color="#999", lw=1, ls="--",
                label="synthetic before")
        ax.plot(np.where(win, d["syn_after"][k], np.nan) / norm, t, color=COLORS[st.name], lw=1.6,
                label="synthetic after")
        ax.set_xlim(-1.3, 1.3)
        ax.set_title(f"{st.name} ({st.angle_min:.0f}-{st.angle_max:.0f} deg)\n"
                     f"r {row[f'corr_before_{st.name}']:.2f} -> {row[f'corr_after_{st.name}']:.2f}")
        if k == 0:
            ax.legend(fontsize=8, loc="lower left")
    lo, hi = max(d["log_twt_ms"].min() - 80, t[0]), min(d["log_twt_ms"].max() + 40, t[-1])
    for ax in axes:
        ax.grid(alpha=0.3)
        for name, tt in zip(d["tops_names"], d["tops_twt_ms"]):
            if lo <= tt <= hi:
                ax.axhline(tt, color="#555", ls=":", lw=0.8)
    for name, tt in zip(d["tops_names"], d["tops_twt_ms"]):
        if lo <= tt <= hi:
            axes[-1].text(1.35, tt, " " + name.replace(" Formation", ""), fontsize=7, va="center")
    axes[0].set_ylim(hi, lo)
    axes[0].set_ylabel("TWT (ms)")
    td = (f"time-depth: {row['td_source']}" + (f" (transferred, {row['td_distance_km']} km)" if row["td_transferred"]
                                              else " (own checkshot-calibrated)"))
    fig.suptitle(f"{well}{' [HELD OUT]' if row['held_out'] else ''}: automated tie   |   {td}   |   "
                 f"shift {row['shift_ms']:+.0f} ms, stretch {row['stretch_pct']:+.1f}%   |   "
                 f"mean r {row['corr_before_mean']:.2f} -> {row['corr_after_mean']:.2f}", weight="bold", fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)


def main() -> int:
    cfg = yaml.safe_load((ROOT / "configs" / "well_tie.yaml").read_text())
    seismic_cfg = yaml.safe_load((ROOT / "configs" / "poseidon_seismic.yaml").read_text())
    petro_cfg = yaml.safe_load((ROOT / "configs" / "petrophysics.yaml").read_text())
    summary, calibration, ties, stack_defs, td_meta = welltie.run(ROOT, cfg, seismic_cfg, petro_cfg)

    scales = {s: v["scale"] for s, v in calibration["stacks"].items()}
    for _, row in summary[summary["status"] == "tied"].iterrows():
        d = np.load(ROOT / "outputs" / "well_ties" / f"{row['well']}.npz")
        plot_tie(row["well"], d, row, stack_defs, scales, ROOT / "outputs" / "well_ties" / f"{row['well']}.png")

    calibration["created"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    (ROOT / "configs" / "calibration.yaml").write_text(
        "# GENERATED by scripts/run_well_tie.py - do not edit by hand\n" + yaml.safe_dump(calibration, sort_keys=False),
        encoding="utf-8")

    tied = summary[summary["status"] == "tied"].copy()
    tied["held_out"] = tied["held_out"].astype(bool)
    train = tied[~tied["held_out"]]
    per_stack = {s.name: float(train[f"corr_after_{s.name}"].mean()) for s in stack_defs}
    g2_pass = np.mean(list(per_stack.values())) >= cfg["auto_tie"]["g2_min_corr"]
    lines = [
        "# Decision log (Poseidon)", "",
        f"## G2 - tie/calibration ({calibration['created']})", "",
        f"**{'PASS' if g2_pass else 'FAIL'}** - mean correlation at training wells after the automated tie: "
        + ", ".join(f"{k} {v:.2f}" for k, v in per_stack.items())
        + f" (threshold {cfg['auto_tie']['g2_min_corr']}).", "",
        f"- Training wells: {', '.join(calibration['training_wells'])}. Held out: {', '.join(calibration['held_out_wells'])}.",
        "- Seismic: near/mid/far 6-18/18-30/30-42 deg, reverse polarity (both from the CGGVeritas processing report). "
        f"Polarity check (mean r): {calibration['polarity_check_mean_corr']}.",
        "- Time-depth: own VSP-calibrated curves for Kronos-1 and Pharos-1; other wells use the nearest eligible "
        "donor (see outputs/well_ties/summary.csv). Transferred curves carry extra uncertainty, absorbed by a bounded "
        "bulk shift and stretch.",
        "- Limitations: TVDSS assumes vertical wells; common amplitude scale between stacks is undocumented (time "
        "variant scaling); wavelets are Ricker estimates; Vs is partly estimated where not measured.", "",
        "| well | held out | TD source | shift ms | stretch % | r before | r after |", "|---|---|---|---|---|---|---|",
    ]
    for _, r in tied.iterrows():
        lines.append(f"| {r['well']} | {r['held_out']} | {r['td_source']}{' (transferred)' if r['td_transferred'] else ''} "
                     f"| {r['shift_ms']:+.0f} | {r['stretch_pct']:+.1f} | {r['corr_before_mean']:.2f} | {r['corr_after_mean']:.2f} |")
    for _, r in summary[summary["status"] != "tied"].iterrows():
        lines.append(f"| {r['well']} | - | {r.get('td_source', '-')} | - | - | - | {r['status']} |")
    (ROOT / "outputs" / "decision_log.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    with pd.option_context("display.width", 250, "display.max_columns", 30):
        print(summary.drop(columns=["window_ms"], errors="ignore").to_string(index=False))
    print("\nWavelets:", {k: (v["freq_hz"], v["phase_deg"]) for k, v in calibration["stacks"].items()})
    print("Polarity check:", calibration["polarity_check_mean_corr"])
    print("G2:", "PASS" if g2_pass else "FAIL", per_stack)
    return 0


if __name__ == "__main__":
    sys.exit(main())
