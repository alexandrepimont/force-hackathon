"""Decision log and markdown report written from pipeline results (every number comes from outputs)."""

from pathlib import Path

from avo import class_names
from avo.pipeline import METHOD_LABELS, METHODS


def _table(df, floatfmt=".3f"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f"{v:{floatfmt}}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def write_decision_log(res, out):
    lines = ["# Decision log", ""]
    for _, d in res["decisions"].iterrows():
        lines.append(f"- **{d['gate']}: {'PASS' if d['passed'] else 'FAIL'}.** {d['detail']}")
    Path(out, "decision_log.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_report(res, wells, cube, out, synthetic):
    s = res["scores"]
    hug = s[s.zone == "hugin"]
    agg_cols = ["balanced_acc", "macro_f1", "log_loss"] + (["oil_sand_f1"] if res["use_fluid"] else [])
    agg = hug.groupby("method")[agg_cols].mean().reset_index()
    agg["method"] = agg["method"].map(METHOD_LABELS)
    per_well = hug.pivot(index="blind_well", columns="method", values="balanced_acc").reset_index()
    cal = res["calib"]
    wav = ", ".join(f"{k}: {v['freq']:.0f} Hz / {v['phase']:.0f} deg" for k, v in cal.wavelets.items())

    lines = [
        "# AVO lithology/fluid workflow: " + ("synthetic concept test" if synthetic else "results"), "",
        "**Question:** do well-anchored simulations predict Hugin lithology and fluid from near/mid/far stacks, "
        "and does a geology prior learned from wells (C) beat hand-picked Monte Carlo ranges (B) and a classical "
        "intercept-gradient interpretation (A) at blind wells?", "",
    ]
    if synthetic:
        lines += [
            "> **This is a synthetic test of the workflow, not a geological result.** The 'earth', wells and seismic "
            "were generated by `avo.synthetic_earth`. Prior C learns from wells drawn from the same synthetic earth, "
            "so its advantage is partly built in. The purpose is to verify that every step runs, that there is no "
            "leakage, and that the evaluation would detect a method that does not work.", "",
        ]
    lines += ["## Decision gates", ""]
    for _, d in res["decisions"].iterrows():
        lines.append(f"- **{d['gate']}: {'PASS' if d['passed'] else 'FAIL'}.** {d['detail']}")
    lines += ["", f"Classes: {', '.join(class_names(res['use_fluid']))}. Estimated wavelets: {wav}.", "",
              "![Well tie](well_tie.png)", "", "![Fluid sensitivity](fluid_sensitivity.png)", "",
              "## Blind-well validation (leave-one-well-out, Hugin zone)", "",
              f"Calibration, prior C and all models were refit without the blind well each time. "
              f"n = {len(wells)} wells: an indication, not statistical proof.", "",
              _table(agg), "", "Balanced accuracy per blind well:", "", _table(per_well), "",
              "![Reliability](reliability.png)", "", "![Crossplot](ig_crossplot.png)", ""]
    lines += [f"![Blind well {w.name}](blind_{w.name}.png)" for w in wells]
    lines += ["", "## Maps", "", "![Maps](maps.png)", "", "![Section](section.png)", ""]
    if res["truth_eval"] is not None:
        te = res["truth_eval"].copy()
        te["method"] = te["method"].map(METHOD_LABELS)
        lines += ["Scores against the known synthetic truth in the map window (all traces):", "", _table(te), ""]
    lines += [
        "## Limitations", "",
        f"- Only {len(wells)} wells; wells in the same structure are not independent.",
        f"- Vs estimated (Greenberg-Castagna) in: "
        f"{', '.join(w.name for w in wells if (w.logs['vs_source'] == 'estimated').any()) or 'none'}.",
        "- Wavelets are Ricker-family estimates; partial stacks are modelled as angle-averaged Aki-Richards.",
        "- Probabilities are conditional on the priors; see the reliability plot before trusting them.",
        "- Thin beds below seismic resolution (e.g. calcite stringers) cannot be predicted as separate classes.",
    ]
    if synthetic:
        lines.append("- Synthetic test only; seismic/log timing relative to production is not modelled.")
    Path(out, "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
